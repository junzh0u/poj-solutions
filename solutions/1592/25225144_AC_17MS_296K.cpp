// Render each command onto a fixed page, writing only nonblank font pixels.
// Center odd widths on column 31; all six C5 columns count for alignment.
#include <iostream>
#include <sstream>
#include <string>
using namespace std;
const char *glyph[27][5] = {
{".***..","*...*.","*****.","*...*.","*...*."},
{"****..","*...*.","****..","*...*.","****.."},
{".****.","*...*.","*.....","*.....",".****."},
{"****..","*...*.","*...*.","*...*.","****.."},
{"*****.","*.....","***...","*.....","*****."},
{"*****.","*.....","***...","*.....","*....."},
{".****.","*.....","*..**.","*...*.",".***.."},
{"*...*.","*...*.","*****.","*...*.","*...*."},
{"*****.","..*...","..*...","..*...","*****."},
{"..***.","...*..","...*..","*..*..",".**..."},
{"*...*.","*..*..","***...","*..*..","*...*."},
{"*.....","*.....","*.....","*.....","*****."},
{"*...*.","**.**.","*.*.*.","*...*.","*...*."},
{"*...*.","**..*.","*.*.*.","*..**.","*...*."},
{".***..","*...*.","*...*.","*...*.",".***.."},
{"****..","*...*.","****..","*.....","*....."},
{".***..","*...*.","*...*.","*..**.",".****."},
{"****..","*...*.","****..","*..*..","*...*."},
{".****.","*.....",".***..","....*.","****.."},
{"*****.","*.*.*.","..*...","..*...",".***.."},
{"*...*.","*...*.","*...*.","*...*.",".***.."},
{"*...*.","*...*.",".*.*..",".*.*..","..*..."},
{"*...*.","*...*.","*.*.*.","**.**.","*...*."},
{"*...*.",".*.*..","..*...",".*.*..","*...*."},
{"*...*.",".*.*..","..*...","..*...","..*..."},
{"*****.","...*..","..*...",".*....","*****."},
{"......","......","......","......","......"}
};
int main() {
    string page[60], line;
    for(int r=0;r<60;++r) page[r]=string(60,'.');
    while(getline(cin,line)) {
        istringstream in(line);
        string cmd,font; int row,col=1;
        in>>cmd;
        if(cmd==".EOP") {
            for(int r=0;r<60;++r) cout<<page[r]<<"\n";
            cout<<"\n"<<string(60,'-')<<"\n\n";
            for(int r=0;r<60;++r) page[r]=string(60,'.');
            continue;
        }
        in>>font>>row;
        if(cmd==".P") in>>col;
        string::size_type a=line.find('|'),b=line.find('|',a+1);
        string text=line.substr(a+1,b-a-1);
        int scale=font=="C5"?6:1, width=int(text.size())*scale;
        if(cmd==".L") col=1;
        if(cmd==".R") col=61-width;
        if(cmd==".C") col=31-width/2;
        --row; --col;
        for(int k=0;k<int(text.size());++k) {
            if(text[k]==' ') continue;
            int h=scale==6?5:1;
            for(int y=0;y<h;++y) for(int x=0;x<scale;++x) {
                char pixel=scale==6?glyph[text[k]-'A'][y][x]:text[k];
                int r=row+y,c=col+k*scale+x;
                if(pixel!='.' && r>=0 && r<60 && c>=0 && c<60) page[r][c]=pixel;
            }
        }
    }
    return 0;
}
